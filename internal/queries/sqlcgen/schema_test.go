//go:build sqlc

package sqlcgen

import (
	"context"
	"flag"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/dure-one/dure-mycart/internal/database"
	"github.com/dure-one/dure-mycart/migrations"
)

var update = flag.Bool("update", false, "rewrite schema/sqlite.sql from the migrations")

const sqliteSchemaFile = "schema/sqlite.sql"

// TestSQLiteSchemaCurrent keeps schema/sqlite.sql equal to the schema the
// migrations produce. sqlc's SQLite parser cannot replay the migration history
// itself (it rejects `ALTER TABLE … DROP COLUMN "name"`), so sqlc reads this
// dump instead. PostgreSQL reads migrations/ directly.
//
// Regenerate after a migration with:
//
//	go test -tags sqlc ./internal/queries/sqlcgen -run TestSQLiteSchemaCurrent -update
func TestSQLiteSchemaCurrent(t *testing.T) {
	conn, err := database.Open(database.Config{
		Driver: database.DriverSQLite,
		DSN:    filepath.Join(t.TempDir(), "schema.db"),
	}, migrations.Embed())
	if err != nil {
		t.Fatalf("open database: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close() })

	got, err := dumpSQLiteSchema(context.Background(), conn)
	if err != nil {
		t.Fatalf("dump schema: %v", err)
	}

	if *update {
		if err := os.WriteFile(sqliteSchemaFile, []byte(got), 0o644); err != nil {
			t.Fatalf("write %s: %v", sqliteSchemaFile, err)
		}
		return
	}

	want, err := os.ReadFile(sqliteSchemaFile)
	if err != nil {
		t.Fatalf("read %s: %v (run with -update)", sqliteSchemaFile, err)
	}
	if string(want) != got {
		t.Fatalf("%s is stale: rerun with -update, then make sqlc-generate", sqliteSchemaFile)
	}
}

// dumpSQLiteSchema renders every table and index the migrations created, in a
// stable order. goose's own bookkeeping table and SQLite internals are left out.
func dumpSQLiteSchema(ctx context.Context, conn *database.Conn) (string, error) {
	rows, err := conn.QueryContext(ctx, `
		SELECT sql FROM sqlite_master
		WHERE sql IS NOT NULL
		  AND name NOT LIKE 'sqlite_%'
		  AND tbl_name != ?
		ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, tbl_name, name`,
		database.MigrateTable)
	if err != nil {
		return "", err
	}
	defer func() { _ = rows.Close() }()

	var b strings.Builder
	b.WriteString("-- Code generated by TestSQLiteSchemaCurrent from migrations/. DO NOT EDIT.\n\n")
	for rows.Next() {
		var stmt string
		if err := rows.Scan(&stmt); err != nil {
			return "", err
		}
		b.WriteString(strings.TrimSpace(stmt))
		b.WriteString(";\n\n")
	}
	return b.String(), rows.Err()
}
